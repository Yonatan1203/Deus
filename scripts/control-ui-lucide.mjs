#!/usr/bin/env node
// Writes web/control/lucide-icons.js: only the Lucide icons the dashboard uses, keyed by the
// dashboard's own names. The output is committed (no runtime dependency, no CDN); re-run after
// changing MAP. Lucide is a devDependency pinned to an exact version.
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const require = createRequire(import.meta.url);
const { icons } = require('lucide');
const { version } = require('lucide/package.json');

// dashboard name → Lucide name
